#!/usr/bin/env python3
"""Build a target-task jsonl from IFEval-style data with verified completions.

IFEval itself (google/IFEval) ships prompts only -- scoring is programmatic, so
there are no reference answers to take a gradient against. Two usable stand-ins:

  argilla   argilla/ifeval-like-data, `filtered` subset: instruction/response
            pairs generated by Qwen2.5-72B-Instruct in IFEval's style and
            verified against lm-evaluation-harness, so the responses actually
            satisfy their constraints. The default.

  personas  allenai/tulu-3-sft-personas-instruction-following, the standalone
            `personahub_ifdata`. Useful as a second target, but note it is also
            inside the Tulu mix -- scoring Tulu against it partly measures
            whether the method retrieves data it was given, which is weaker
            evidence than it looks.

    python prepare_target.py --source argilla --n 500 --out data/target_if.jsonl
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from datasets import load_dataset

def from_argilla(row: dict, idx: int) -> dict | None:
    if not row.get("prompt_level_strict_acc"):
        return None
    prompt = (row.get("prompt") or "").strip()
    completion = (row.get("response") or "").strip()
    if not prompt or not completion:
        return None
    return {"id": f"target_argilla:{idx}", "prompt": prompt,
            "completion": completion, "source": "ifeval-like"}

def from_personas(row: dict, idx: int) -> dict | None:
    messages = row.get("messages") or []
    user = next((m for m in messages if m.get("role") == "user"), None)
    assistant = next((m for m in messages if m.get("role") == "assistant"), None)
    if user is None or assistant is None:
        return None

    prompt = (user.get("content") or "").strip()
    completion = (assistant.get("content") or "").strip()
    if not prompt or not completion:
        return None
    return {"id": f"target_personas:{idx}", "prompt": prompt,
            "completion": completion, "source": "personas-if"}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", default="argilla", choices=["argilla", "personas"])
    ap.add_argument("--n", type=int, default=500,
                    help="target examples to keep; a few hundred is plenty, "
                         "since these get averaged into a direction")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    args.out.parent.mkdir(parents=True, exist_ok=True)

    if args.source == "argilla":
        # `filtered` holds the rows whose responses passed verification.
        stream = load_dataset("argilla/ifeval-like-data", "filtered",
                              split="train", streaming=True)
        convert = from_argilla
    else:
        stream = load_dataset("allenai/tulu-3-sft-personas-instruction-following",
                              split="train", streaming=True)
        convert = from_personas

    stream = stream.shuffle(seed=args.seed, buffer_size=10_000)

    rows, skipped = [], 0
    for idx, row in enumerate(stream):
        if len(rows) >= args.n:
            break
        converted = convert(row, idx)
        if converted is None:
            skipped += 1
            continue
        rows.append(converted)

    with open(args.out, "w") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(f"wrote {len(rows)} target examples to {args.out} ({skipped} skipped)")
    if rows:
        example = rows[0]
        print(f"\nexample prompt:     {example['prompt'][:200]}")
        print(f"example completion: {example['completion'][:200]}")


if __name__ == "__main__":
    main()
